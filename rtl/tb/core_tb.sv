    64'h19000300000000ff,  // 0x19 mov | rd=0 R0 | rs1=0 | rs2=0 w=3 .b | imm28=0xff (255)
    64'h190000000fffffff,  // 0x19 mov | rd=0 R0 | rs1=0 | rs2=0 w=0 | imm28=0x0fffffff (-1)
    64'h1900020000001234,  // 0x19 mov | rd=0 R0 | rs1=0 | rs2=0 w=2 .w | imm28=0x1234 (4660)
    64'h0100000000000000   // 0x01 halt
  };

  // -- P2: §3.1 ALU immediate ------------------------------------------------
  localparam logic [XLEN-1:0] P2 [11] = '{
    64'h1900000000000064,  // mov R0, 100
    64'h1010000000000032,  // 0x10 add | rd=1 R1 | rs1=0 R0 | w=0 | imm28=50
    64'h1121000000000019,  // 0x11 sub | rd=2 R2 | rs1=1 R1 | w=0 | imm28=25
    64'h1232000000000004,  // 0x12 mul | rd=3 R3 | rs1=2 R2 | w=0 | imm28=4
    64'h14430000000000ff,  // 0x14 and | rd=4 R4 | rs1=3 R3 | w=0 | imm28=255
    64'h1554000000000100,  // 0x15 or  | rd=5 R5 | rs1=4 R4 | w=0 | imm28=256
    64'h166500000000000f,  // 0x16 xor | rd=6 R6 | rs1=5 R5 | w=0 | imm28=15
    64'h1776000000000002,  // 0x17 shl | rd=7 R7 | rs1=6 R6 | w=0 | imm28=2
    64'h1887000000000001,  // 0x18 shr | rd=8 R8 | rs1=7 R7 | w=0 | imm28=1
