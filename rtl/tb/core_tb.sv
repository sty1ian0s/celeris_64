    check64("P8 §3.2.2 select merge result", dbg_sel_result, 64'h0);
    check1 ("P8 §3.2.2 select result low bit", dbg_sel_result_lo, 1'b0);

    if (prog_failures == 0) $display("  PASS P8 (§3 operand slicing, all groups)");

    // ------------------------------------------------------------------
    // P9 — §7 diagnostics: each refusal is its own named signal
    // ------------------------------------------------------------------
    $display("");
    $display("-- P9: §7 named diagnostics for each refusal class --");
    prog_failures = 0;

    // §3.1 divide-by-zero is a diagnostic, not a trap.
    reset_core();
    image_clear();
    // div R1, R2, R3 register form (imm28 == 0) with rs2 = R3 = 0.
    image_write64(0, 64'h1312_3000_0000_0000);
    step_instruction_discard();
    check1 ("P9 §3.1 divide-by-zero flagged", lat_err_div_zero, 1'b1);
    check1 ("P9 divide-by-zero stopped the machine", halted, 1'b1);
    check64("P9 divide-by-zero wrote nothing", regs_or_gpr(1), 64'h0);

    // §5 reserved width encoding.
    reset_core();
    image_clear();
    // mov R1, 1 with width = 4 (reserved).
    image_write64(0, 64'h1901_0400_0000_0001);
    step_instruction_discard();
    check1 ("P9 §5 reserved width flagged", lat_err_reserved_width, 1'b1);
    check64("P9 reserved width wrote nothing", regs_or_gpr(1), 64'h0);

    // §3.4 stream refusal (chunk = 0).
    reset_core();
    image_clear();
    // stream.add R0, [R1]+0, R0 -> chunk 0 is a §3.4 mistake.
    image_write64(0, 64'h4001_0000_0000_0000);
    step_instruction_discard();
    check1 ("P9 §3.4 zero chunk flagged", lat_err_stream, 1'b1);

    // §3.3 field refusal (width = 0).
    reset_core();
    image_clear();
    image_write64(0, 64'h3001_0000_0000_0000);   // field.extract offset=0 width=0
    step_instruction_discard();
    check1 ("P9 §3.3 zero width flagged", lat_err_field, 1'b1);

    if (prog_failures == 0) $display("  PASS P9 (§7 named diagnostics)");

    // ------------------------------------------------------------------
    // P10 — §3.2.1 compare writes the status enum (the only sanctioned result)
    // ------------------------------------------------------------------
    $display("");
    $display("-- P10: §3.2.1 compare materialises the status enum into rd --");
    prog_failures = 0;
    reset_core();
    image_clear();
    // mov R2, 5 ; mov R3, 7 ; compare R1, R2, R3 -> R2 < R3 signed => LESS = 1
    image_write64(0,  64'h1920_0000_0000_0005);   // mov R2, 5
    image_write64(8,  64'h1930_0000_0000_0007);   // mov R3, 7
    image_write64(16, 64'h2012_3000_0000_0000);   // compare R1, R2, R3 (register form)
    step_instruction_discard();
    step_instruction_discard();
    step_instruction_discard();
    check1 ("P10 §3.2.1 status enum low bit (LESS=1)", lat_comp_status_lo, 1'b1);
    check64("P10 §3.2.1 compare wrote the enum", u_core.u_regfile.gpr_q[1], 64'h1);
    if (prog_failures == 0) $display("  PASS P10 (§3.2.1 status enum)");

    report_and_finish();
  end

  //===========================================================================
  // Step one instruction and ignore whether it retired (used where the expected
  // outcome is a stall, a halt or a refusal).
  //===========================================================================
  // The core is in its decode state, i.e. ready to accept a word.
  function automatic logic state_is_decode();
    state_is_decode = (u_core.state_q == 3'd0);
  endfunction

  // Wait for the core to return to DECODE (or park), so a multi-cycle unit is
  // never interrupted by the next fetch.
  task automatic wait_for_decode_or_stop(output logic stopped);
    int unsigned g;
    begin
      stopped = 1'b0;
      g = 0;
      while (!state_is_decode() && !halted && g < 64) begin
        @(posedge clk); #1;
        if (mem_wr_en) begin
          for (int unsigned b = 0; b < 8; b++) begin
            if (mem_byte_sel[b]) image[32'(mem_wr_addr[9:0]) + b] = mem_wr_data[8*b +: 8];
          end
        end
        g++;
      end
      if (halted) stopped = 1'b1;
    end
  endtask

  task automatic step_instruction_discard();
    logic discarded_retired, discarded_stopped;
    begin
      step_instruction(discarded_retired, discarded_stopped);
      if (discarded_retired) ever_retired = 1'b1;
      if (discarded_stopped) ever_stopped = 1'b1;
      // Both are consumed so the diagnostic paths are observable, not dangling.
      if (ever_retired && ever_stopped) observed_both = 1'b1;
    end
  endtask

  // The GPRs after a step, for checks taken mid-program.
  function automatic logic [XLEN-1:0] regs_or_gpr(input int unsigned i);
    begin
      regs_or_gpr = (i < 12) ? gpr[i] : {XLEN{1'b0}};
    end
  endfunction

  //===========================================================================
  // §3.6 Amendment 1.1: every normative opcode in 0x60-0x8F is recognised, and
  // every other byte in the range is RESERVED and must not be.
  //===========================================================================
  task automatic check_recognised_table();
    int unsigned recognised_count;
    logic        expect_known;
    begin
      recognised_count = 0;
      for (int unsigned b = 32'h60; b <= 32'h8F; b++) begin
        reset_core();
        image_clear();
        // opcode | rd=1 | rs1=2 | reserved=0 | count=0   (rs2=rs3=0, count=0)
        image_write64(0, (64'(b) << 56) | (64'd1 << 52) | (64'd2 << 48));
        step_instruction_discard();

        // §3.6 table: 0x60-0x64, 0x70-0x73, 0x80-0x83.
        expect_known = (b <= 8'h64) || (b >= 8'h70 && b <= 8'h73)
                    || (b >= 8'h80 && b <= 8'h83);
        if (expect_known) begin
          recognised_count++;
          if (lat_acc_recognised !== 1'b1) begin
            failures++; prog_failures++;
            $display("    FAIL §3.6 opcode 0x%02x should be RECOGNISED", b);
          end
        end else begin
          if (lat_acc_recognised !== 1'b0) begin
            failures++; prog_failures++;
            $display("    FAIL §3.6 RESERVED opcode 0x%02x was recognised as a neighbour", b);
          end
          if (lat_err_accel_unknown !== 1'b1) begin
            failures++; prog_failures++;
            $display("    FAIL §3.6 RESERVED opcode 0x%02x did not raise unknown_op", b);
          end
        end
        checks++;
      end
      $display("      ok §3.6 all 13 normative opcodes recognised (%0d), 35 reserved rejected",
               recognised_count);
    end
  endtask

  //===========================================================================
  // Helper tasks used by the sequence above.
  //===========================================================================
  task automatic reset_core();
    begin
      rst_ni      = 1'b0;
      fetch_valid = 1'b0;
      obs_req     = 1'b0;
      repeat (2) @(posedge clk);
      #1;
      rst_ni = 1'b1;
      @(posedge clk);
      #1;
    end
  endtask

  task automatic run_to_halt();
    logic r, s;
    begin
      retired_count = 0;
      forever begin
        step_instruction(r, s);
        if (r) retired_count++;
        if (s) disable run_to_halt;
        // A parked machine with no retirement is also a terminal condition.
        if (halted) disable run_to_halt;
        if (retired_count > 200) begin
          $display("    FAIL run_to_halt exceeded 200 instructions");
          failures++;
          disable run_to_halt;
        end
      end
    end
  endtask

  task automatic report_and_finish();
    begin
      $display("");
      // Both retirement and stop paths must have been exercised, or part of the
      // testbench never ran and the pass count would be misleading.
      if (!observed_both) begin
        $display("    FAIL neither/both of retired and stopped paths were exercised");
        failures++;
      end
      checks++;
      $display("=== checks=%0d failures=%0d ===", checks, failures);
      if (failures == 0) begin
        $display("PASS: all %0d core vectors matched (simulation only; RTL is NOT synthesized, NOT timing-closed, NOT on silicon)", checks);
        $finish;
      end else begin
        $display("FAIL: %0d of %0d core vectors mismatched", failures, checks);
        $fatal(1, "core_tb failed: %0d mismatched vector(s)", failures);
      end
    end
  endtask

endmodule
