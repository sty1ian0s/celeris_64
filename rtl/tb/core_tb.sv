  logic [RS2_W-1:0] dbg_sel_rs2_idx_unused;

  //===========================================================================
  // Clock. 10 ns period — testbench stimulus only. NO frequency claim.
  //===========================================================================
  initial clk = 1'b0;
  always #5 clk = ~clk;

  //===========================================================================
  // Pass/fail bookkeeping. A `$fatal` on the first mismatch would hide how many
  // vectors agreed, so failures are counted and reported.
  //===========================================================================
  int unsigned checks = 0;
  int unsigned failures = 0;
  int unsigned prog_failures = 0;

  task automatic check64(input string name, input logic [XLEN-1:0] got, input logic [XLEN-1:0] exp);
    begin
      checks++;
      if (got !== exp) begin
        failures++;
        prog_failures++;
        $display("    FAIL %-40s got=0x%016x exp=0x%016x", name, got, exp);
      end else begin
        $display("      ok %-40s = 0x%016x", name, got);
      end
    end
  endtask

  task automatic check1(input string name, input logic got, input logic exp);
    begin
      checks++;
      if (got !== exp) begin
        failures++;
        prog_failures++;
        $display("    FAIL %-40s got=%0b exp=%0b", name, got, exp);
      end else begin
        $display("      ok %-40s = %0b", name, got);
      end
    end
  endtask

  //===========================================================================
  // Memory helpers. Little-endian, §1 / AGENTS.md §2.2.
  //===========================================================================
  task automatic image_clear();
    begin
      for (int unsigned i = 0; i < IMAGE_BYTES; i++) image[i] = 8'h00;
    end
  endtask

  // Loads a 64-bit word at a byte address, least-significant byte first.
  task automatic image_write64(input int unsigned addr, input logic [XLEN-1:0] w);
    begin
      for (int unsigned b = 0; b < 8; b++) image[addr + b] = w[8*b +: 8];
    end
  endtask

  function automatic logic [XLEN-1:0] image_read64(input int unsigned addr);
    logic [XLEN-1:0] w;
    begin
      w = {XLEN{1'b0}};
      for (int unsigned b = 0; b < 8; b++) w[8*b +: 8] = image[addr + b];
      image_read64 = w;
    end
  endfunction

  // Fetches from the current PC. `fetch_word` is what the core sees.
  always_comb fetch_word = image_read64(32'(pc[9:0]));

  // The §3.4 stream engine's byte port, served from the same image.
  always_comb begin
    mem_rd_data = {XLEN{1'b0}};
    for (int unsigned b = 0; b < 8; b++) begin
      mem_rd_data[8*b +: 8] = image[32'(mem_rd_addr[9:0]) + b];
    end
  end

  //===========================================================================
  // Program loading. Each program is a list of REAL encoded words.
  //===========================================================================
  task automatic load_program(input int unsigned base, input int unsigned n,
                              input logic [XLEN-1:0] words []);
    begin
      for (int unsigned i = 0; i < n; i++) image_write64(base + 8*i, words[i]);
    end
  endtask

  // Latched diagnostics from the decode cycle. The core's err_* outputs are gated
  // on fetch_valid_i because they describe the word currently being decoded, so
  // they must be captured WHILE that word is presented — reading them later shows
  // the idle state, which reports every diagnostic as clear.
  logic        lat_err_accel_not_impl, lat_err_accel_unknown, lat_err_accel_reserved;
  logic        lat_err_div_zero, lat_err_reserved_width, lat_err_stream;
  logic        lat_err_field, lat_err_unimplemented, lat_err_alu_zero;
  logic        lat_err_sel_reserved;
  logic        lat_acc_recognised;
  logic        lat_is_nop;
  logic        lat_comp_status_lo;
  logic [OPERAND_W-1:0] lat_operand;
  logic [63:0] lat_control_target, lat_pc_next;
  logic [3:0]  lat_alu_rs2, lat_alu_width, lat_stream_elem_width;
  logic        lat_alu_is_imm, lat_alu_src2_is_imm, lat_alu_op_legal;
  logic        lat_fld_op_legal, lat_sel_op_legal;
  logic        lat_fld_zero_width_ok;
  logic        lat_acc_rs2_used, lat_acc_rs3_used, lat_acc_count_derived;
  logic        lat_acc_in_range, lat_acc_group_matrix, lat_acc_group_fft;
  logic        lat_acc_group_codec, lat_acc_result_valid;
  logic [7:0]  lat_acc_reserved;
  logic [3:0]  lat_acc_rs2, lat_acc_rs3;
  logic [31:0] lat_acc_count;
  logic [3:0]  lat_sel_match, lat_sel_true_idx, lat_sel_false_idx;
  logic [27:0] lat_alu_imm28;
  logic [11:0] lat_alu_zero;
  logic [7:0]  lat_fld_offset, lat_fld_width;
  logic [3:0]  lat_fld_src2_idx;
  logic [19:0] lat_stream_chunk, lat_stream_reserved;
  logic [3:0]  lat_stream_rs2_idx;

  //===========================================================================
  // Run one instruction to completion, serving its memory traffic.
  //
  // The core asserts fetch_valid when it wants the word at pc; this drives one
  // cycle at a time and, while the stream engine is busy, performs the byte
  // read/write the engine asks for. Returns when the instruction retires or the
  // machine stops on a diagnostic.
  //===========================================================================
  task automatic step_instruction(output logic retired_now, output logic stopped);
    logic done;
    int unsigned guard;
    begin
      retired_now = 1'b0;
      stopped     = 1'b0;
      done        = 1'b0;
      guard       = 0;

      // Present the fetched word. `retired_o` and `halted_o` are COMBINATIONAL
      // functions of the state register, so they are sampled in the settled part
      // of the cycle BEFORE the next posedge — sampling after the edge would see
      // the following state and miss the one-cycle retirement pulse entirely.
      // Present the fetched word only while the core is in DECODE. Re-asserting it
      // during ST_STREAMW would ask the core to decode a second instruction while
      // the stream engine is still walking the first.
      if (state_is_decode()) fetch_valid = 1'b1;
      else                   fetch_valid = 1'b0;
      #1;

      while (!done && guard < 64) begin
        guard++;

        // Serve the stream engine's memory traffic for THIS cycle.
        if (mem_wr_en && (mem_wr_addr[XLEN-1:10] != 0)) begin
          failures++; prog_failures++;
          $display("    FAIL stream write address 0x%0x exceeds the image", mem_wr_addr);
        end
        if (mem_rd_en && (mem_rd_addr[XLEN-1:10] != 0)) begin
          failures++; prog_failures++;
          $display("    FAIL stream read address 0x%0x exceeds the image", mem_rd_addr);
        end
        if (mem_wr_en) begin
          for (int unsigned b = 0; b < 8; b++) begin
            if (mem_byte_sel[b]) begin
              image[32'(mem_wr_addr[9:0]) + b] = mem_wr_data[8*b +: 8];
            end
          end
        end
        if (mem_rd_en)   stream_reads_served++;
        if (busy)        stream_busy_cycles++;

        // Capture the decode-cycle diagnostics and taps. These are valid ONLY
        // while fetch_valid is asserted (the first iteration of this loop); later
        // iterations run with fetch_valid low and would overwrite them with the
        // idle all-clear values.
        if (fetch_valid) begin
        lat_err_accel_not_impl = err_accel_not_impl;
        lat_err_accel_unknown  = err_accel_unknown;
        lat_err_accel_reserved = err_accel_reserved;
        lat_err_div_zero       = err_div_zero;
        lat_err_reserved_width = err_reserved_width;
        lat_err_stream         = err_stream;
        lat_err_field          = err_field;
        lat_err_unimplemented  = err_unimplemented;
        lat_err_alu_zero       = err_alu_zero;
        lat_err_sel_reserved   = err_sel_reserved;
        lat_acc_recognised     = dbg_acc_recognised;
        lat_is_nop             = dbg_is_nop;
        lat_operand            = dbg_operand;
        lat_comp_status_lo     = dbg_comp_status_lo;
        lat_sel_reserved       = dbg_sel_reserved;
        lat_fld_reserved       = dbg_fld_reserved;
        lat_control_target     = dbg_control_target;
        lat_pc_next            = dbg_pc_next;
        lat_alu_rs2            = dbg_alu_rs2;
        lat_alu_width          = dbg_alu_width;
        lat_alu_is_imm         = {dbg_alu_is_imm};
        lat_alu_src2_is_imm    = {dbg_alu_src2_is_imm};
        lat_alu_op_legal       = {dbg_alu_op_legal};
        lat_fld_offset         = dbg_fld_offset;
        lat_fld_width          = dbg_fld_width;
        lat_fld_src2_idx       = dbg_fld_src2_idx;
        lat_stream_chunk       = dbg_stream_chunk;
        lat_stream_reserved    = dbg_stream_reserved;
        lat_stream_rs2_idx     = dbg_stream_rs2_idx;
        lat_stream_elem_width  = dbg_stream_elem_width;
        lat_fld_op_legal       = dbg_fld_op_legal;
        lat_sel_op_legal       = dbg_sel_op_legal;
        lat_fld_zero_width_ok  = dbg_fld_no_zero_width;
        lat_acc_rs2_used       = dbg_acc_rs2_used;
        lat_acc_rs3_used       = dbg_acc_rs3_used;
        lat_acc_count_derived  = dbg_acc_count_derived;
        lat_acc_in_range       = dbg_acc_in_range;
        lat_acc_group_matrix   = dbg_acc_group_matrix;
        lat_acc_group_fft      = dbg_acc_group_fft;
        lat_acc_group_codec    = dbg_acc_group_codec;
        lat_acc_result_valid   = dbg_acc_result_valid;
        lat_acc_reserved       = dbg_acc_reserved;
        lat_acc_rs2            = dbg_acc_rs2;
        lat_acc_rs3            = dbg_acc_rs3;
        lat_acc_count          = dbg_acc_count;
        lat_sel_match          = dbg_sel_match;
        lat_sel_true_idx       = dbg_sel_true_idx;
        lat_sel_false_idx      = dbg_sel_false_idx;
        lat_alu_imm28          = dbg_alu_imm28;
        lat_alu_zero           = dbg_alu_zero;
        end

        // Sample this cycle's outcome before advancing the clock. A `halt`
        // retires AND stops: ST_HALTWB asserts retired_o, then the machine parks
        // in ST_HALTED. Both are reported so run_to_halt counts the halt as a
        // retired instruction exactly as src/vm.zig does.
        if (halted) begin
          stopped     = 1'b1;
          retired_now = retired;   // halt is itself a retired instruction
          done        = 1'b1;
        end else if (retired) begin
          retired_now = 1'b1;
          done        = 1'b1;
        end

        if (!done) begin
          @(posedge clk);
          #1;
        end
      end

      // Retire the fetch request and let the next instruction see a fresh word.
      fetch_valid = 1'b0;
      @(posedge clk);
      #1;

      if (guard >= 64) begin
        failures++;
        prog_failures++;
        $display("    FAIL instruction at PC=0x%0x never settled (guard expired)", pc);
      end
    end
  endtask

  //===========================================================================
  // §4 register snapshot, in §4 index order.
  //===========================================================================
  logic [XLEN-1:0] regs [16];

  task automatic snapshot_regs();
    int unsigned guard;
    begin
      // Ask the core for a fresh 16-entry §4 snapshot and wait for it. The sweep
      // runs only while no instruction is in flight, so it cannot perturb state.
      obs_req = 1'b1;
      guard   = 0;
      while (!obs_ready && guard < 40) begin
        @(posedge clk); #1;
        guard++;
      end
      if (!obs_ready) begin
        failures++;
        $display("    FAIL observation sweep never completed (guard expired)");
      end
      obs_req = 1'b0;
      @(posedge clk); #1;

      for (int unsigned i = 0; i < 12; i++) regs[i] = gpr[i];
      regs[12] = sp;
      regs[13] = lr;
      regs[14] = pc;
      regs[15] = flags;
    end
  endtask

  //===========================================================================
  // Program words. The §2 split of each is given in the comment:
  //   opcode | rd | rs1 | operand
  //===========================================================================

  // -- P1: §5 sub-width zero-extension --------------------------------------
  // From /tmp/p1_zeroext.bin, produced by the Zig assembler.
