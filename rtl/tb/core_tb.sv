//=============================================================================
// core_tb.sv — CLS64 top-level core testbench (Verilator --binary)
//
// Drives REAL ENCODED INSTRUCTION WORDS through rtl/core.sv and checks the
// resulting architectural register file WORD FOR WORD against the verified Zig
// simulator (zig-out/bin/celeris64). See rtl/CROSSCHECK.md for the reference
// outputs and the exact commands that produced them.
//
// FOUR PROGRAMS, each a real program the Zig VM also ran:
//   P1 §5 sub-width zero-extension   (mov .w / .l / .b must clear the upper bits)
//   P2 §3.1 ALU immediate            (the ten ops on immediates)
//   P3 §3.0 jump / call / ret        (LR MUST be the address of the NEXT insn)
//   P4 §3.4 stream.add               (fused load/add/store, pointer auto-advance)
//
// The instruction words below are the LITERAL BYTES the Zig assembler emitted,
// pasted in. They are not generated by the RTL and not read back from the DUT, so
// a wrong encoding fails instead of agreeing with itself. Each word is also
// written with its §2 field split in the comments so a reader can check it by hand.
//
// TESTBENCH-ONLY constructs in this file: `initial`, `#` delays and `$display`.
// rtl/ synthesizable modules contain none of them. There is deliberately NO
// `timescale` — the RTL is forbidden one and a testbench-local timescale makes
// the tool raise TIMESCALEMOD against every module that lacks it.
//
// FIDELITY (docs/isa-encoding.md §8): SIMULATION of a lint-verified specification.
// NEVER synthesized, never timing-closed, never on silicon. The clock period below
// is testbench STIMULUS, not a timing result; NO clock frequency is claimed.
//
// LIMIT (matching rtl/core.sv's header): memory and the instruction fetch live
// here, so `stream.*` is walked by this testbench. Each instruction is settled to
// completion before the next is issued — there is no scoreboard, so a program that
// read a register mid-stream would read a stale value. The four programs below are
// straight-line and never do that.
//=============================================================================

