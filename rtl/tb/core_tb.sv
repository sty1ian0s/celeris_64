    64'h0100000000000000   // halt
  };

  // -- P3: §3.0 jump / call / ret (LR correctness) ---------------------------
  localparam logic [XLEN-1:0] P3 [9] = '{
    64'h1910000000000009,  // mov R1, 9
    64'h0300000000000028,  // 0x03 call | rd=0 | rs1=0 | imm48=40  -> LR = 8+8 = 16, PC = 40
